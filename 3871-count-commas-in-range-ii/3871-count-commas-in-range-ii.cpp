class Solution {
public:
    long long countCommas(long long n) {
        long long int ans=0;
        if(n>=1000 && n<=999999){
            ans+=n-1000+1;
        }
        else if(n>=1000000 && n<=999999999){
            ans+=((n-1000000+1)*2)+999999-1000+1;
        }
        else if(n>=1000000000 && n<=999999999999){
            ans+=((n-1000000000+1)*3)+((999999999-1000000+1)*2)+999999-1000+1;
        }
        else if(n>=1000000000000 && n<=999999999999999){
            ans+=((n-1000000000000+1)*4)+((999999999999-1000000000+1)*3)+((999999999-1000000+1)*2)+999999-1000+1;
        }
        else if(n==1000000000000000){
            ans+=((999999999999999-1000000000000+1)*4)+((999999999999-1000000000+1)*3)+((999999999-1000000+1)*2)+999999-1000+1+5;
        }
        return ans;
    }
};